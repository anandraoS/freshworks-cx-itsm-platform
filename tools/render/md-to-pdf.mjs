// Markdown-subset -> PDF renderer (pdfkit). Two passes so the table of contents carries real page numbers.
// Usage: node md-to-pdf.mjs --out out.pdf --title "T" --subtitle "S" [--chapter-break h1] in1.md in2.md ...
// Supported: # ## ### headings, paragraphs, - / 1. lists (2 levels), fenced code, pipe tables, > callouts, images, **bold**, *italic*, `code`.
import PDFDocument from 'pdfkit';
import fs from 'node:fs';
import path from 'node:path';

const args = process.argv.slice(2);
let out = 'out.pdf', title = 'Document', subtitle = '', files = [], repoRoot = process.cwd();
for (let i = 0; i < args.length; i++) {
  if (args[i] === '--out') out = args[++i];
  else if (args[i] === '--title') title = args[++i];
  else if (args[i] === '--subtitle') subtitle = args[++i];
  else if (args[i] === '--root') repoRoot = args[++i];
  else files.push(args[i]);
}

const FONT = { r: 'C:/Windows/Fonts/arial.ttf', b: 'C:/Windows/Fonts/arialbd.ttf', i: 'C:/Windows/Fonts/ariali.ttf', bi: 'C:/Windows/Fonts/arialbi.ttf', m: 'C:/Windows/Fonts/consola.ttf', mb: 'C:/Windows/Fonts/consolab.ttf' };
const FOOT1 = 'Generated by AI. AI can make mistakes. Validate before relying upon this document.';
const FOOT2 = '\u00A9 2026 Cotiviti, Inc. All rights reserved. All proprietary information shall remain the sole and exclusive property of Cotiviti, Inc.';
const C = { ink: '#1b2430', accent: '#0b5cad', muted: '#5b6675', codeBg: '#f3f5f8', codeBorder: '#d5dbe3', callBg: '#eaf2fb', th: '#0b5cad', zebra: '#f7f9fc' };

// Replace glyphs missing from Arial/Consolas with safe equivalents.
function clean(s) {
  return s.replace(/\r/g, '')
    .replace(/[\u2192\u21D2]/g, '->').replace(/\u2190/g, '<-').replace(/\u2194/g, '<->')
    .replace(/\u2265/g, '>=').replace(/\u2264/g, '<=').replace(/\u2260/g, '!=')
    .replace(/[\u2713\u2714]/g, 'yes').replace(/[\u2717\u2718]/g, 'no')
    .replace(/[\u200B\uFE0F]/g, '').replace(/\u00A0/g, ' ')
    .replace(/[\u2500-\u257F]/g, '-').replace(/\u2022/g, '-');
}

function parse(md) {
  const lines = clean(md).split('\n'); const blocks = []; let i = 0;
  while (i < lines.length) {
    const l = lines[i];
    if (/^```/.test(l)) { const lang = l.slice(3).trim(); const buf = []; i++; while (i < lines.length && !/^```/.test(lines[i])) buf.push(lines[i++]); i++; blocks.push({ t: 'code', lang, text: buf.join('\n') }); continue; }
    const h = /^(#{1,3})\s+(.*)$/.exec(l);
    if (h) { blocks.push({ t: 'h', level: h[1].length, text: h[2].trim().replace(/[`*]/g, '') }); i++; continue; }
    const im = /^!\[(.*?)\]\((.*?)\)\s*$/.exec(l);
    if (im) { blocks.push({ t: 'img', cap: im[1], src: im[2] }); i++; continue; }
    if (/^\s*\|/.test(l) && i + 1 < lines.length && /^\s*\|?\s*:?-{2,}/.test(lines[i + 1])) {
      const rows = []; while (i < lines.length && /^\s*\|/.test(lines[i])) { rows.push(lines[i]); i++; }
      const split = r => r.trim().replace(/^\|/, '').replace(/\|$/, '').split(/(?<!\\)\|/).map(c => c.trim().replace(/\\\|/g, '|'));
      blocks.push({ t: 'table', head: split(rows[0]), rows: rows.slice(2).map(split) }); continue;
    }
    if (/^>\s?/.test(l)) { const buf = []; while (i < lines.length && /^>\s?/.test(lines[i])) buf.push(lines[i++].replace(/^>\s?/, '')); blocks.push({ t: 'call', text: buf.join(' ') }); continue; }
    const li = /^(\s*)([-*]|\d+\.)\s+(.*)$/.exec(l);
    if (li) { const items = []; while (i < lines.length) { const m = /^(\s*)([-*]|\d+\.)\s+(.*)$/.exec(lines[i]); if (!m) { if (/^\s{2,}\S/.test(lines[i]) && items.length) { items[items.length - 1].text += ' ' + lines[i].trim(); i++; continue; } break; } items.push({ lvl: m[1].length >= 2 ? 1 : 0, num: /\d/.test(m[2]) ? m[2] : null, text: m[3] }); i++; } blocks.push({ t: 'list', items }); continue; }
    if (!l.trim() || /^-{3,}s*$/.test(l)) { i++; continue; }
    const buf = [l.trim()]; i++;
    while (i < lines.length && lines[i].trim() && !/^(#{1,3}\s|```|>|\s*\||!\[|\s*([-*]|\d+\.)\s)/.test(lines[i])) buf.push(lines[i++].trim());
    blocks.push({ t: 'p', text: buf.join(' ') });
  }
  return blocks;
}

function inline(text) { // -> [{s, f}]
  const segs = []; const re = /(\*\*[^*]+\*\*|`[^`]+`|(?<![*\w])\*[^*\s][^*]*\*(?!\w))/g; let last = 0, m;
  while ((m = re.exec(text))) { if (m.index > last) segs.push({ s: text.slice(last, m.index), f: 'r' }); const t = m[0]; if (t.startsWith('**')) segs.push({ s: t.slice(2, -2), f: 'b' }); else if (t.startsWith('`')) segs.push({ s: t.slice(1, -1), f: 'm' }); else segs.push({ s: t.slice(1, -1), f: 'i' }); last = m.index + t.length; }
  if (last < text.length) segs.push({ s: text.slice(last), f: 'r' });
  return segs;
}

const allBlocks = files.flatMap(f => parse(fs.readFileSync(f, 'utf8')));
const tocEntries = allBlocks.filter(b => b.t === 'h' && b.level <= 2);
const TOC_PER_PAGE = 40;
const tocPages = Math.max(1, Math.ceil((tocEntries.length + 1) / TOC_PER_PAGE));

function render(pageMap) {
  const doc = new PDFDocument({ size: 'A4', margins: { top: 56, bottom: 64, left: 54, right: 54 }, bufferPages: true, info: { Title: title, Author: 'CX-ITSM portfolio project', Subject: subtitle } });
  const chunks = []; doc.on('data', c => chunks.push(c));
  for (const [k, v] of Object.entries(FONT)) doc.registerFont(k, v);
  const W = () => doc.page.width - doc.page.margins.left - doc.page.margins.right;
  const X = () => doc.page.margins.left;
  const bottom = () => doc.page.height - doc.page.margins.bottom;
  const headings = []; const ensure = h => { if (doc.y + h > bottom()) doc.addPage(); };
  const pageIdx = () => doc.bufferedPageRange().count - 1;

  // runs: write inline segments with wrapping
  function runs(text, { size = 10, color = C.ink, x = X(), width = W(), gap = 4, base = 'r', align = 'left' } = {}) {
    const segs = inline(text); doc.fillColor(color).fontSize(size);
    segs.forEach((sg, idx) => { const font = sg.f === 'r' ? base : sg.f === 'm' ? 'm' : (base === 'b' ? 'b' : sg.f); doc.font(font).fontSize(sg.f === 'm' ? size - 0.7 : size); const o = { continued: idx < segs.length - 1, width, align, lineGap: 2 }; if (idx === 0) doc.text(sg.s, x, doc.y, o); else doc.text(sg.s, o); });
    doc.moveDown(0).y += gap;
  }
  const heightOf = (text, { size = 10, width = W(), base = 'r' } = {}) => { doc.font(base).fontSize(size); return doc.heightOfString(text.replace(/\*\*|`/g, ''), { width, lineGap: 2 }); };

  // ---------- cover ----------
  doc.rect(0, 0, doc.page.width, 250).fill(C.accent);
  doc.fillColor('#ffffff').font('b').fontSize(30).text(title, 54, 90, { width: doc.page.width - 108 });
  doc.font('r').fontSize(14).fillColor('#dbe8f7').text(subtitle, 54, doc.y + 12, { width: doc.page.width - 108 });
  doc.fillColor(C.ink).font('r').fontSize(11);
  doc.y = 290;
  const note = [
    'Portfolio project inspired by the public job description for a Lead Full Stack Engineer (IC3). It does not reproduce, and makes no claim about, any proprietary software, architecture or production system of any company.',
    'Honesty notice: all test, benchmark and measurement figures in this document come from commands actually executed on a single developer laptop (local profile: H2, in-memory cache and relay). Components that need Docker (PostgreSQL, Redis, RabbitMQ, MongoDB, Grafana, k6, Testcontainers) were not available and are labelled "not executed" wherever they appear.',
    'The AI assistant is a deterministic, rule-based mock provider. It is not machine learning, and a real provider is optional and disabled by default.'];
  note.forEach(n => { doc.font('r').fontSize(10.5).fillColor(C.muted).text(n, 54, doc.y, { width: W() }); doc.moveDown(0.8); });
  doc.fillColor(C.muted).fontSize(10).text('Generated ' + new Date().toISOString().slice(0, 10), 54, doc.y + 8);

  // ---------- TOC (reserved pages) ----------
  const tocStart = pageIdx() + 1;
  for (let p = 0; p < tocPages; p++) doc.addPage();
  doc.addPage();
  const pageOffset = 0;

  // ---------- body ----------
  let chapterStarted = false;
  for (const b of allBlocks) {
    if (b.t === 'h') {
      if (b.level === 1) { if (chapterStarted || doc.y > doc.page.margins.top + 5) doc.addPage(); chapterStarted = true; }
      const size = b.level === 1 ? 22 : b.level === 2 ? 15 : 12;
      ensure(size * 2 + 40);
      if (b.level === 1) { doc.y += 4; }
      else doc.y += b.level === 2 ? 10 : 6;
      const y0 = doc.y; doc.fillColor(b.level === 3 ? C.ink : C.accent).font('b').fontSize(size).text(b.text, X(), y0, { width: W() });
      if (b.level === 1) { doc.moveTo(X(), doc.y + 3).lineTo(X() + W(), doc.y + 3).lineWidth(1.5).strokeColor(C.accent).stroke(); doc.y += 12; } else doc.y += 4;
      if (b.level <= 2) { headings.push({ level: b.level, text: b.text, page: pageIdx() }); }
      if (b.level <= 2) doc.outline.addItem(b.text);
    } else if (b.t === 'p') { ensure(heightOf(b.text) > 120 ? 40 : heightOf(b.text) + 4); runs(b.text, { gap: 6 }); }
    else if (b.t === 'list') {
      for (const it of b.items) { const ind = 14 + it.lvl * 16; const h = heightOf(it.text, { width: W() - ind }); ensure(Math.min(h, 60) + 2); const y0 = doc.y; doc.fillColor(C.accent).font('b').fontSize(10).text(it.num ? it.num : '\u2022', X() + it.lvl * 16, y0, { width: 14, lineBreak: false }); doc.y = y0; runs(it.text, { x: X() + ind, width: W() - ind, gap: 2 }); }
      doc.y += 4;
    }
    else if (b.t === 'call') { const h = heightOf(b.text, { width: W() - 24 }) + 14; ensure(Math.min(h, 80)); const y0 = doc.y; doc.rect(X(), y0, W(), h).fill(C.callBg); doc.rect(X(), y0, 3, h).fill(C.accent); doc.y = y0 + 7; runs(b.text, { x: X() + 12, width: W() - 24, gap: 0 }); doc.y = y0 + h + 8; }
    else if (b.t === 'code') {
      doc.font('m').fontSize(7.8); const cw = doc.widthOfString('M'); const maxc = Math.floor((W() - 14) / cw);
      const lines = b.text.split('\n').flatMap(l => { l = l.replace(/\t/g, '    '); if (l.length <= maxc) return [l]; const o = []; for (let k = 0; k < l.length; k += maxc) o.push((k ? '  ' : '') + l.slice(k, k + maxc - (k ? 2 : 0))); return o; });
      const lh = 10.2; let idx = 0;
      doc.y += 2;
      while (idx < lines.length) { const room = Math.floor((bottom() - doc.y - 12) / lh); if (room < 3) { doc.addPage(); continue; } const take = Math.min(room, lines.length - idx); const y0 = doc.y; doc.rect(X(), y0, W(), take * lh + 10).fillAndStroke(C.codeBg, C.codeBorder); doc.fillColor(C.ink).font('m').fontSize(7.8); for (let k = 0; k < take; k++) doc.text(lines[idx + k] || ' ', X() + 7, y0 + 5 + k * lh, { lineBreak: false }); idx += take; doc.y = y0 + take * lh + 14; }
    }
    else if (b.t === 'table') {
      const n = b.head.length; const lens = b.head.map((h, c) => Math.min(60, Math.max(h.length, ...b.rows.map(r => (r[c] || '').length), 4)));
      const tot = lens.reduce((a, c) => a + Math.sqrt(c) * 3 + 4, 0); const ws = lens.map(l => (Math.sqrt(l) * 3 + 4) / tot * W());
      const size = n > 6 ? 7.2 : n > 4 ? 8 : 8.8; const pad = 4;
      const rowH = (cells, base) => Math.max(...cells.map((c, k) => { doc.font(base).fontSize(size); return doc.heightOfString(c.replace(/\*\*|`/g, ''), { width: ws[k] - pad * 2, lineGap: 1 }); })) + pad * 2;
      const drawRow = (cells, y, h, head, zebra) => { let x = X(); cells.forEach((c, k) => { if (head) doc.rect(x, y, ws[k], h).fill(C.th); else { doc.rect(x, y, ws[k], h).fillAndStroke(zebra ? C.zebra : '#ffffff', C.codeBorder); } doc.fillColor(head ? '#ffffff' : C.ink).font(head ? 'b' : 'r').fontSize(size).text(c.replace(/\*\*|`/g, ''), x + pad, y + pad, { width: ws[k] - pad * 2, lineGap: 1 }); x += ws[k]; }); };
      doc.y += 2; let first = true;
      const hh = rowH(b.head, 'b');
      ensure(hh + 30); { const y0 = doc.y; drawRow(b.head, y0, hh, true); doc.y = y0 + hh; }
      b.rows.forEach((r, ri) => { const cells = b.head.map((_, k) => r[k] || ''); const h = rowH(cells, 'r'); if (doc.y + h > bottom()) { doc.addPage(); const yh = doc.y; drawRow(b.head, yh, hh, true); doc.y = yh + hh; } const yr = doc.y; drawRow(cells, yr, h, false, ri % 2 === 1); doc.y = yr + h; });
      doc.y += 10;
    }
    else if (b.t === 'img') {
      let p = path.resolve(repoRoot, b.src); if (!fs.existsSync(p)) { const alt = path.resolve(repoRoot, "docs/diagrams/png", path.basename(b.src)); if (fs.existsSync(alt)) p = alt; }
      if (!fs.existsSync(p)) { runs('[missing image: ' + b.src + ']', { color: '#b00020' }); continue; }
      const img = doc.openImage(p); const maxW = W(); const maxH = bottom() - doc.page.margins.top - 60;
      let sc = Math.min(maxW / img.width, maxH / img.height, 1.6); let w = img.width * sc, h = img.height * sc;
      if (doc.y + h + 28 > bottom()) { doc.addPage(); }
      const availH = bottom() - doc.y - 28; if (h > availH) { sc = availH / img.height; w = img.width * sc; h = img.height * sc; }
      doc.image(p, X() + (maxW - w) / 2, doc.y, { width: w, height: h }); doc.y += h + 4;
      doc.font('i').fontSize(8.5).fillColor(C.muted).text(b.cap, X(), doc.y, { width: W(), align: 'center' }); doc.y += 12;
    }
  }

  // ---------- fill TOC ----------
  const range = doc.bufferedPageRange();
  const bodyHeadings = headings;
  doc.switchToPage(tocStart);
  doc.y = doc.page.margins.top;
  doc.fillColor(C.accent).font('b').fontSize(20).text('Contents', X(), doc.y); doc.y += 10;
  let tocPageNo = 0, line = 0;
  const tocRows = bodyHeadings;
  tocRows.forEach(h => {
    if (line >= TOC_PER_PAGE - 1 && tocPageNo < tocPages - 1) { tocPageNo++; doc.switchToPage(tocStart + tocPageNo); doc.y = doc.page.margins.top; line = 0; }
    const y = doc.y; const ind = h.level === 2 ? 14 : 0; const pg = pageMap ? (pageMap.get(h.text + '#' + h.level + '#' + tocRows.indexOf(h)) ?? '') : '';
    doc.font(h.level === 1 ? 'b' : 'r').fontSize(h.level === 1 ? 10 : 9).fillColor(h.level === 1 ? C.ink : C.muted).text(h.text, X() + ind, y, { width: W() - ind - 40, lineBreak: false, ellipsis: true });
    doc.text(String(pg === '' ? '' : pg), X() + W() - 36, y, { width: 36, align: 'right', lineBreak: false });
    doc.y = y + (h.level === 1 ? 14.5 : 12.5); line++;
  });

  // ---------- footers ----------
  const total = range.count;
  for (let p = 1; p < total; p++) {
    doc.switchToPage(p); const m = doc.page.margins.bottom; doc.page.margins.bottom = 0;
    const y = doc.page.height - 52;
    doc.moveTo(X(), y - 4).lineTo(X() + W(), y - 4).lineWidth(0.4).strokeColor(C.codeBorder).stroke();
    doc.font('i').fontSize(6.6).fillColor('#7a8594').text(FOOT1, X(), y, { width: W(), align: 'left', lineBreak: false });
    doc.text(FOOT2, X(), y + 9, { width: W(), align: 'left', lineBreak: false });
    doc.font('r').fontSize(7.5).fillColor(C.muted).text(title.length > 70 ? title.slice(0, 67) + '...' : title, X(), y + 22, { width: W() - 60, lineBreak: false });
    doc.text('Page ' + (p), X() + W() - 60, y + 22, { width: 60, align: 'right', lineBreak: false });
    doc.page.margins.bottom = m;
  }
  doc.flushPages();
  return new Promise(res => { doc.on('end', () => res({ buf: Buffer.concat(chunks), headings: bodyHeadings, pages: total })); doc.end(); });
}

const first = await render(null);
const pm = new Map(); first.headings.forEach((h, i) => pm.set(h.text + '#' + h.level + '#' + i, h.page));
const second = await render(pm);
fs.writeFileSync(out, second.buf);
console.log(JSON.stringify({ out, pages: second.pages, headings: second.headings.length, bytes: second.buf.length }));
