create table ticket (
    id                    uuid                     not null,
    tenant_id             uuid                     not null,
    number                bigint                   not null,
    type                  varchar(20)              not null,
    title                 varchar(200)             not null,
    description           varchar(8000)            not null,
    status                varchar(20)              not null,
    priority              varchar(10)              not null,
    severity              varchar(10)              not null,
    category_id           uuid,
    tags                  varchar(500)             not null default ',',
    requester_id          uuid                     not null,
    assignee_id           uuid,
    created_at            timestamp with time zone not null,
    updated_at            timestamp with time zone not null,
    first_response_due_at timestamp with time zone,
    resolution_due_at     timestamp with time zone,
    first_responded_at    timestamp with time zone,
    resolved_at           timestamp with time zone,
    sla_status            varchar(12)              not null default 'ON_TRACK',
    sla_paused_at         timestamp with time zone,
    sla_checked_at        timestamp with time zone,
    breach_notified       boolean                  not null default false,
    escalation_level      integer                  not null default 0,
    reopen_count          integer                  not null default 0,
    version               bigint                   not null default 0,
    constraint pk_ticket primary key (id),
    constraint fk_ticket_tenant foreign key (tenant_id) references organization (id),
    -- composite FKs: a ticket can only reference users/categories of its own tenant
    constraint fk_ticket_requester foreign key (tenant_id, requester_id) references app_user (tenant_id, id),
    constraint fk_ticket_assignee foreign key (tenant_id, assignee_id) references app_user (tenant_id, id),
    constraint fk_ticket_category foreign key (tenant_id, category_id) references ticket_category (tenant_id, id),
    constraint uq_ticket_tenant_number unique (tenant_id, number),
    constraint uq_ticket_tenant_id unique (tenant_id, id),
    constraint ck_ticket_type check (type in ('SUPPORT', 'IT_SERVICE')),
    constraint ck_ticket_status check (status in ('NEW', 'OPEN', 'PENDING', 'ON_HOLD', 'RESOLVED', 'CLOSED', 'REOPENED')),
    constraint ck_ticket_priority check (priority in ('LOW', 'MEDIUM', 'HIGH', 'URGENT')),
    constraint ck_ticket_severity check (severity in ('MINOR', 'MAJOR', 'CRITICAL')),
    constraint ck_ticket_sla_status check (sla_status in ('ON_TRACK', 'AT_RISK', 'BREACHED', 'MET', 'PAUSED')),
    constraint ck_ticket_escalation check (escalation_level >= 0),
    constraint ck_ticket_reopen check (reopen_count >= 0)
);
